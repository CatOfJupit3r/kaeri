import { getModelForClass, index, modelOptions, prop } from '@typegoose/typegoose';
import type { DocumentType } from '@typegoose/typegoose';

import { RequiredTimeStamps } from '../base-classes';
import { ObjectIdString } from '../helpers';

@modelOptions({ schemaOptions: { collection: 'script_versions', timestamps: true } })
@index({ scriptId: 1, version: -1 })
@index({ scriptId: 1, contentHash: 1 })
@index({ scriptId: 1, autoGenerated: 1, version: 1 })
class ScriptVersionClass extends RequiredTimeStamps {
  @prop({ default: () => ObjectIdString() })
  public _id!: string;

  @prop({ required: true })
  public scriptId!: string;

  @prop({ required: true })
  public version!: number;

  @prop({ required: true })
  public content!: string;

  @prop({ required: true })
  public contentHash!: string;

  @prop({ required: true })
  public createdBy!: string;

  @prop()
  public name?: string;

  @prop({ required: true, default: true })
  public autoGenerated!: boolean;

  @prop({ type: () => Number })
  public wordCount?: number;

  @prop({ type: () => Number })
  public blockCount?: number;
}

export const ScriptVersionModel = getModelForClass(ScriptVersionClass);
export type ScriptVersionDoc = DocumentType<ScriptVersionClass>;
