import { oc } from '@orpc/contract';
import z from 'zod';

import { authProcedure } from './procedures';

const paginationSchema = z.object({
  limit: z.number().int().min(1).max(100).default(20),
  offset: z.number().int().min(0).default(0),
});

const scriptSchema = z.object({
  _id: z.string(),
  seriesId: z.string(),
  title: z.string(),
  authors: z.array(z.string()).optional(),
  genre: z.string().optional(),
  logline: z.string().optional(),
  coverUrl: z.string().url().optional(),
  content: z.string(),
  lastEditedAt: z.coerce.date(),
});

const scriptSummarySchema = scriptSchema.pick({
  _id: true,
  seriesId: true,
  title: true,
  authors: true,
  genre: true,
  logline: true,
  coverUrl: true,
  lastEditedAt: true,
});

export const createScriptInputSchema = z.object({
  seriesId: z.string(),
  title: z.string().min(1),
  authors: z.array(z.string()).optional(),
  genre: z.string().optional(),
  logline: z.string().optional(),
  coverUrl: z.string().url().optional(),
});

export const updateScriptPatchSchema = z
  .object({
    title: z.string().min(1).optional(),
    authors: z.array(z.string()).optional(),
    genre: z.string().optional(),
    logline: z.string().optional(),
    coverUrl: z.string().url().optional(),
  })
  .refine((value) => Object.keys(value).length > 0, 'At least one field must be provided');

const createScript = authProcedure
  .route({
    path: '/create',
    method: 'POST',
    summary: 'Create a script',
    description: 'Creates a script under a series with metadata and empty content.',
  })
  .input(createScriptInputSchema)
  .output(scriptSchema);

const updateScript = authProcedure
  .route({
    path: '/update',
    method: 'PUT',
    summary: 'Update script metadata',
    description: 'Updates script metadata fields (title, authors, genre, logline, cover).',
  })
  .input(
    z.object({
      scriptId: z.string(),
      patch: updateScriptPatchSchema,
    }),
  )
  .output(scriptSchema);

const deleteScript = authProcedure
  .route({
    path: '/delete',
    method: 'DELETE',
    summary: 'Delete a script',
    description:
      'Deletes a script if permitted. Implementations should ensure references (appearances) are handled safely.',
  })
  .input(z.object({ scriptId: z.string() }))
  .output(z.object({ success: z.boolean() }));

const listScriptsBySeries = authProcedure
  .route({
    path: '/list-by-series',
    method: 'GET',
    summary: 'List scripts by series',
    description: 'Returns paginated scripts for a series.',
  })
  .input(paginationSchema.merge(z.object({ seriesId: z.string() })))
  .output(z.object({ items: z.array(scriptSummarySchema), total: z.number() }));

const getScript = authProcedure
  .route({
    path: '/get',
    method: 'GET',
    summary: 'Get a script',
    description: 'Returns a script with metadata and content.',
  })
  .input(z.object({ scriptId: z.string() }))
  .output(scriptSchema);

const saveScriptContent = authProcedure
  .route({
    path: '/save-content',
    method: 'PUT',
    summary: 'Save script content (autosave/manual)',
    description: 'Saves plaintext script content and returns updated lastEditedAt.',
  })
  .input(
    z.object({
      scriptId: z.string(),
      content: z.string(),
      cursor: z.object({ line: z.number().int().min(0), column: z.number().int().min(0) }).optional(),
    }),
  )
  .output(z.object({ lastEditedAt: z.coerce.date() }));

const exportScriptPdf = authProcedure
  .route({
    path: '/export-pdf',
    method: 'GET',
    summary: 'Export script as PDF',
    description: 'Exports a screenplay-formatted PDF for a script. Should validate saved state before export.',
  })
  .input(z.object({ scriptId: z.string() }))
  .output(z.object({ ok: z.literal(true), fileType: z.literal('application/pdf') }));

// --- Version Management ---

const scriptVersionSummarySchema = z.object({
  _id: z.string(),
  scriptId: z.string(),
  version: z.number().int(),
  name: z.string().optional(),
  createdBy: z.string(),
  createdAt: z.coerce.date(),
  autoGenerated: z.boolean(),
  wordCount: z.number().int().optional(),
  blockCount: z.number().int().optional(),
});

const scriptVersionSchema = scriptVersionSummarySchema.extend({
  content: z.string(),
});

const listScriptVersions = authProcedure
  .route({
    path: '/versions/list',
    method: 'GET',
    summary: 'List script versions',
    description: 'Returns paginated version history for a script.',
  })
  .input(paginationSchema.merge(z.object({ scriptId: z.string() })))
  .output(z.object({ items: z.array(scriptVersionSummarySchema), total: z.number() }));

const getScriptVersion = authProcedure
  .route({
    path: '/versions/get',
    method: 'GET',
    summary: 'Get a specific script version',
    description: 'Returns full content for a specific version snapshot.',
  })
  .input(z.object({ scriptId: z.string(), versionId: z.string() }))
  .output(scriptVersionSchema);

const createScriptVersion = authProcedure
  .route({
    path: '/versions/create',
    method: 'POST',
    summary: 'Create a script version',
    description: 'Snapshots the current script content as a named version. Deduplicates by content hash.',
  })
  .input(z.object({ scriptId: z.string(), name: z.string().optional() }))
  .output(scriptVersionSummarySchema);

const restoreScriptVersion = authProcedure
  .route({
    path: '/versions/restore',
    method: 'POST',
    summary: 'Restore a script version',
    description: 'Restores script content to a previous version. Creates a safety snapshot of the current state first.',
  })
  .input(z.object({ scriptId: z.string(), versionId: z.string() }))
  .output(z.object({ restoredVersion: z.number().int(), safetySnapshotId: z.string() }));

const deleteScriptVersion = authProcedure
  .route({
    path: '/versions/delete',
    method: 'DELETE',
    summary: 'Delete a script version',
    description: 'Permanently deletes a specific version snapshot.',
  })
  .input(z.object({ scriptId: z.string(), versionId: z.string() }))
  .output(z.object({ success: z.boolean() }));

const updateScriptVersion = authProcedure
  .route({
    path: '/versions/update',
    method: 'PUT',
    summary: 'Update a script version name',
    description: 'Renames a version snapshot.',
  })
  .input(z.object({ scriptId: z.string(), versionId: z.string(), name: z.string().max(100) }))
  .output(scriptVersionSummarySchema);

const scriptsContract = oc.prefix('/scripts').router({
  createScript,
  updateScript,
  deleteScript,
  listScriptsBySeries,
  getScript,
  saveScriptContent,
  exportScriptPdf,
  listScriptVersions,
  getScriptVersion,
  createScriptVersion,
  restoreScriptVersion,
  deleteScriptVersion,
  updateScriptVersion,
});

export default scriptsContract;
export { scriptSchema, scriptSummarySchema, scriptVersionSummarySchema, scriptVersionSchema };
